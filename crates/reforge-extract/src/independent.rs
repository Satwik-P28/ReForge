//! Narrow independent implementation generation.
//!
//! The generated artifact is a Python program with the observed machine
//! embedded as code-adjacent data. It does not read `twin.json`, does not start
//! the reference application, and can execute arbitrary action sequences over
//! modeled states. Unmodeled cells still return `unknown`; this is not a claim
//! of domain CRUD inference that the investigation never observed.

use reforge_types::BehavioralTwin;
use serde_json::json;

pub fn render_independent_implementation(twin: &BehavioralTwin) -> String {
    let transitions: Vec<serde_json::Value> = twin
        .transitions
        .iter()
        .map(|t| {
            json!({
                "id": t.id.to_string(),
                "from": t.from,
                "to": t.to,
                "action": t.action,
                "guard": t.guard,
                "updates": t.updates,
                "outputs": t.outputs,
                "events": t.events,
                "error": t.error,
                "certainty": t.certainty,
            })
        })
        .collect();
    let variables: Vec<serde_json::Value> = twin
        .variables
        .values()
        .map(|v| json!({"name": v.name, "type": v.ty, "initial": v.initial}))
        .collect();
    let invariants: Vec<serde_json::Value> = twin
        .invariants
        .iter()
        .map(|i| json!({"id": i.id.to_string(), "expression": i.expression}))
        .collect();
    let states: Vec<&str> = twin.states.keys().map(String::as_str).collect();
    let machine = json!({
        "initial_state": twin.initial_state,
        "states": states,
        "variables": variables,
        "transitions": transitions,
        "invariants": invariants,
    });
    let encoded = serde_json::to_string(&machine).expect("machine is serializable");
    // A JSON string literal is also a valid Python string literal here; the
    // generated program parses it once with the standard library.
    let quoted = serde_json::to_string(&encoded).expect("machine JSON is a string");
    TEMPLATE.replace("__MACHINE_JSON__", &quoted)
}

const TEMPLATE: &str = r#"#!/usr/bin/env python3
"""Independent executable implementation generated by ReForge.

The observed state machine is embedded in this file. It does not load the
extracted twin artifact, run the source application, or replay a captured trace: arbitrary
sequences over modeled states execute through the generated transition logic.
Cells that were never observed return `unknown`; domain CRUD semantics that the
investigation did not observe are not invented.

Usage:
    python3 implementation.py --state .reforge-impl add title=unseen
    python3 implementation.py --state .reforge-impl --inspect
    python3 implementation.py --state .reforge-impl --reset
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass, field
from typing import Any

MACHINE = json.loads(__MACHINE_JSON__)
INITIAL_STATE = MACHINE["initial_state"]
STATES = set(MACHINE["states"])


@dataclass
class State:
    """Typed runtime carrier for the modeled abstract state and variables."""

    name: str
    variables: dict[str, Any] = field(default_factory=dict)


def initial_variables() -> dict[str, Any]:
    values: dict[str, Any] = {}
    for variable in MACHINE["variables"]:
        values[variable["name"]] = variable.get("initial")
    return values


def _loads_param(text: str) -> Any:
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return text


def _guard_ok(guard: Any, params: dict[str, Any]) -> bool:
    """Evaluate the narrow observed guard dialect: input.x == literal [and ...]."""
    if guard is None:
        return True
    if not isinstance(guard, str):
        return False
    for clause in guard.split(" and "):
        left, separator, right = clause.partition("==")
        if not separator:
            return False
        left = left.strip()
        if not left.startswith("input."):
            return False
        name = left[len("input."):]
        try:
            expected = json.loads(right.strip())
        except json.JSONDecodeError:
            return False
        if params.get(name) != expected:
            return False
    return True


def _eval(expression: Any, state: State, params: dict[str, Any]) -> Any:
    if isinstance(expression, dict):
        op = expression.get("op")
        if op == "lit_string":
            return expression.get("value")
        if op == "lit_int":
            return int(expression.get("value", 0))
        if op == "lit_float":
            return float(expression.get("value", 0.0))
        if op == "lit_bool":
            return bool(expression.get("value", False))
        if op == "input":
            return params.get(expression.get("name"))
        if op == "var":
            return state.variables.get(expression.get("name"))
        return None
    return expression


def _check_invariants(state: State) -> list[str]:
    violations: list[str] = []
    for invariant in MACHINE["invariants"]:
        # Invariant expressions outside the observed literal subset are kept
        # visible as unsupported rather than silently satisfied.
        expression = invariant.get("expression")
        if isinstance(expression, dict) and expression.get("op") == "lit_bool":
            if not expression.get("value"):
                violations.append(str(invariant.get("id")))
        elif expression is not None:
            violations.append(str(invariant.get("id")))
    return violations


def perform(state: State, action: str, params: dict[str, Any]) -> dict[str, Any]:
    candidates = [
        t for t in MACHINE["transitions"]
        if t["from"] == state.name and t["action"] == action
    ]
    successes = [
        t for t in candidates
        if not t.get("error") and _guard_ok(t.get("guard"), params)
    ]
    if len(successes) > 1:
        return {
            "outcome": "hypothesis_conflict",
            "state": state.name,
            "candidates": [t["id"] for t in successes],
        }
    if successes:
        transition = successes[0]
        previous = state.name
        state.name = transition.get("to", previous)
        for name, expression in (transition.get("updates") or {}).items():
            state.variables[name] = _eval(expression, state, params)
        outputs = {
            name: _eval(expression, state, params)
            for name, expression in (transition.get("outputs") or {}).items()
        }
        violations = _check_invariants(state)
        if violations:
            return {
                "outcome": "invariant_violation",
                "state": state.name,
                "invariants": violations,
            }
        return {
            "outcome": "success",
            "previous_state": previous,
            "state": state.name,
            "events": transition.get("events", []),
            "outputs": outputs,
            "transition": transition["id"],
        }
    errors = [
        t for t in candidates
        if t.get("error") and _guard_ok(t.get("guard"), params)
    ]
    if errors:
        return {
            "outcome": "rejected",
            "state": state.name,
            "error": errors[0].get("error"),
        }
    return {
        "outcome": "unknown",
        "state": state.name,
        "detail": "no modeled transition for this action in this state",
    }


def _state_path(directory: str) -> str:
    return os.path.join(directory, "state.json")


def _load_state(directory: str) -> State:
    path = _state_path(directory)
    if not os.path.exists(path):
        return State(INITIAL_STATE, initial_variables())
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    return State(payload.get("state", INITIAL_STATE), payload.get("variables") or initial_variables())


def _save_state(directory: str, state: State, history: list[dict[str, Any]]) -> None:
    os.makedirs(directory, exist_ok=True)
    with open(_state_path(directory), "w", encoding="utf-8") as handle:
        json.dump(
            {"state": state.name, "variables": state.variables, "history": history},
            handle,
            sort_keys=True,
            indent=2,
        )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--state", default=".reforge-impl")
    parser.add_argument("--inspect", action="store_true")
    parser.add_argument("--reset", action="store_true")
    parser.add_argument("action", nargs="?")
    parser.add_argument("params", nargs="*")
    args = parser.parse_args(argv)

    if args.reset:
        path = _state_path(args.state)
        if os.path.exists(path):
            os.remove(path)
        print(json.dumps({"reset": True, "state": INITIAL_STATE}, sort_keys=True))
        return 0

    state = _load_state(args.state)
    history_path = _state_path(args.state)
    history: list[dict[str, Any]] = []
    if os.path.exists(history_path):
        with open(history_path, "r", encoding="utf-8") as handle:
            history = json.load(handle).get("history", [])

    if args.inspect:
        print(json.dumps(
            {
                "state": state.name,
                "variables": state.variables,
                "actions": sorted({t["action"] for t in MACHINE["transitions"]}),
                "history": history,
            },
            sort_keys=True,
        ))
        return 0

    if not args.action:
        parser.error("an action is required unless --inspect or --reset is used")

    params: dict[str, Any] = {}
    for pair in args.params:
        if "=" not in pair:
            parser.error("parameters must be key=value")
        key, value = pair.split("=", 1)
        params[key] = _loads_param(value)

    result = perform(state, args.action, params)
    result["parameters"] = params
    history.append(
        {"action": args.action, "params": params, "outcome": result["outcome"], "state": state.name}
    )
    _save_state(args.state, state, history)
    print(json.dumps(result, sort_keys=True))
    return 0 if result["outcome"] in ("success", "rejected") else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
"#;
